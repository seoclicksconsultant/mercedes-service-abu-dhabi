"""Generate assets/css/luxe.css: the dark-luxury theme layer.

It scans the light-theme stylesheets and re-points every rule that paints
dark text (var(--obsidian)) or a white surface, then appends the hand-written
luxury styling from _src/luxe_manual.css. Run by build.py on every build.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ["assets/css/style.css", "assets/css/home.css", "assets/css/service.css"]

WHITE_BG = re.compile(r"background(?:-color)?\s*:\s*(#fff\b|#ffffff\b|var\(--polar\)|rgb\(255 255 255 / \.(?:7|8|9)\d*\)|linear-gradient\(180deg, #fff, var\(--paper\)\)|linear-gradient\(180deg, #fff, var\(--paper\)\))")
INK = re.compile(r"(?<![-\w])color\s*:\s*var\(--obsidian\)")
SKIP = ("btn", "swatch__chip span", "loader", "cone__car", "rel__go", "skip", "showroom__tab[aria-selected", "symf__b.is-on", "subnav__links a.is-active", "dec__tab[aria-selected")

def rules(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", text):
        sel = m.group(1).strip()
        if sel.startswith("@") or re.fullmatch(r"(from|to|[\d.%, ]+)", sel):
            continue
        sel = re.sub(r"^.*\{\s*", "", sel)
        yield sel, m.group(2)

def build():
    ink, surf = [], []
    for f in CSS:
        for sel, body in rules((ROOT / f).read_text(encoding="utf-8")):
            parts = [s.strip() for s in sel.split(",")]
            parts = [p for p in parts if not any(k in p for k in SKIP)]
            if not parts:
                continue
            if INK.search(body):
                ink += parts
            if WHITE_BG.search(body):
                surf += parts
    dedupe = lambda xs: list(dict.fromkeys(xs))
    out = ["/* ===== GENERATED by _src/luxe_gen.py: do not edit this block by hand ===== */"]
    out.append(",\n".join(dedupe(ink)) + " { color: var(--ink); }")
    out.append(",\n".join(dedupe(surf)) + " { background: var(--surface); }")
    out.append("/* ===== END GENERATED ===== */\n")
    manual = (ROOT / "_src/luxe_manual.css").read_text(encoding="utf-8")
    (ROOT / "assets/css/luxe.css").write_text("\n".join(out) + "\n\n" + manual, encoding="utf-8")

if __name__ == "__main__":
    build()
